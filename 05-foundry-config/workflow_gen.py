# The provisioner wrote your project's endpoint here. Override it with
# the FOUNDRY_PROJECT_ENDPOINT environment variable if you move projects.
PROJECT_ENDPOINT = os.environ.get(
    "FOUNDRY_PROJECT_ENDPOINT", "{endpoint}")

DEFAULT_TASK = "Build me a FastAPI service that returns a random quote about NVIDIA."


def build_workflow():
    """One FoundryAgent per step, in config order."""
