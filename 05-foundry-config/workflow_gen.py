def generate_workflow(config, out_dir: str, versions: dict | None = None,
                      config_name: str = "foundry.yaml") -> str:
    """Write workflow.py for the config's sequential orchestration.

    `versions` maps agent name -> version string (from the
    provisioner's create_version calls); "1" when unknown. Returns
    the path written. Raises ValueError when the config is not in
    sequential mode.
    """
    if not config.orchestration or config.orchestration.mode != "sequential":
        raise ValueError(
            "generate_workflow needs orchestration.mode 'sequential' "
            "(this config uses "
            f"{config.orchestration.mode if config.orchestration else 'none'!r})")
    versions = versions or {}
    lines = []
    for step in config.orchestration.steps:
        agent = config.agent(step)
        version = versions.get(step, "1")
        lines.append(
            f'        FoundryAgent(project_endpoint=PROJECT_ENDPOINT,'
            f'\n                       agent_name="{agent.name}",'
            f'\n                       agent_version="{version}",'
            f'\n                       credential=credential),')
    participants = "\n".join(lines)
    text = HEADER.format(
        config_name=config_name,
        steps=", ".join(config.orchestration.steps),
        endpoint=config.project.endpoint,
        participants=participants,
    )
    # The file must be valid Python before it is written.
    compile(text, "workflow.py", "exec")
    path = os.path.join(out_dir, "workflow.py")
    with open(path, "w") as f:
        f.write(text)
    return path
